'use strict';

// npx mocha tests/config.test.js
//
// Guards against the brand accidentally reverting to "MiroTalk" on a future
// `git merge upstream/master` (see deploy/README.md "Fork maintenance").

require('should');

const fs = require('fs');
const path = require('path');

describe('config.js brand (VCPeer rebrand)', () => {
    const configPath = path.join(__dirname, '..', 'app', 'src', 'config.js');

    before(function () {
        if (!fs.existsSync(configPath)) {
            this.skip(); // config.js is generated by `npm run prestart`, not committed
        }
    });

    it('resolves brand.app.name to VCPeer', () => {
        delete require.cache[require.resolve('../app/src/config.js')];
        const config = require('../app/src/config.js');
        config.brand.app.name.should.equal('VCPeer');
    });

    it('resolves brand.og.url to https://vcpeer.com', () => {
        delete require.cache[require.resolve('../app/src/config.js')];
        const config = require('../app/src/config.js');
        config.brand.og.url.should.equal('https://vcpeer.com');
    });

    it('resolves brand.og.siteName to VCPeer', () => {
        delete require.cache[require.resolve('../app/src/config.js')];
        const config = require('../app/src/config.js');
        config.brand.og.siteName.should.equal('VCPeer');
    });

    it('never falls back to the upstream MiroTalk sponsor/support sections', () => {
        delete require.cache[require.resolve('../app/src/config.js')];
        const config = require('../app/src/config.js');
        config.brand.html.topSponsors.should.equal(false);
        config.brand.html.sponsors.should.equal(false);
        config.brand.html.pastSponsors.should.equal(false);
        config.brand.html.advertisers.should.equal(false);
        config.brand.html.supportUs.should.equal(false);
        config.brand.html.poweredBy.should.equal(false);
    });
});

describe('config.template.js source (brand, not generated)', () => {
    const templatePath = path.join(__dirname, '..', 'app', 'src', 'config.template.js');
    const source = fs.readFileSync(templatePath, 'utf8');

    it('does not contain the literal "MiroTalk" brand string in the brand block', () => {
        // Extract just the `brand: { ... }` block body for a scoped check so we
        // don't false-positive on unrelated parts of the file.
        const brandStart = source.indexOf('brand: {');
        brandStart.should.be.above(-1);
        const brandBlock = source.slice(brandStart, source.indexOf('\n    // =========', brandStart + 20));
        brandBlock.should.not.match(/MiroTalk/);
    });

    it('sets app.name to VCPeer', () => {
        source.should.match(/name:\s*'VCPeer'/);
    });
});
